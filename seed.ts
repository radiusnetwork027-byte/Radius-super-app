function cover(title: string, c1: string, c2: string) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="1000"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop stop-color="${c1}"/><stop offset="1" stop-color="${c2}"/></linearGradient></defs><rect width="100%" height="100%" fill="url(#g)"/><circle cx="620" cy="180" r="90" fill="rgba(255,255,255,0.08)"/><text x="48" y="860" fill="white" font-size="42" font-family="Inter,sans-serif" font-weight="700">${title}</text></svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

const now = Date.now();

function friend(opts: {
  id: string;
  phone: string;
  name: string;
  username: string;
  bio: string;
  color: string;
  dLat: number;
  dLon: number;
  place: string;
  battery: number;
  charging?: boolean;
  gold?: boolean;
  agoMin: number;
}): Profile {
  return blankProfile({
    id: opts.id,
    phone: opts.phone,
    full_name: opts.name,
    username: opts.username,
    bio: opts.bio,
    color: opts.color,
    lat: ABUJA.lat + opts.dLat,
    lon: ABUJA.lon + opts.dLon,
    accuracy: 8,
    place_name: opts.place,
    battery_level: opts.battery,
    battery_charging: !!opts.charging,
    last_seen: now - opts.agoMin * 60_000,
    is_gold: !!opts.gold,
    is_verified: !!opts.gold,
    demo: true,
    onboard_step: "done",
    share_battery: true,
    perm_location: true,
    perm_battery: true,
  });
}

